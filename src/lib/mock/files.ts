// What the mock's `fileUrl` hands out. The real server streams the file of the user's video folder
// with its own type (`GET /api/file`: ranged MP4s for `<video>`, the image as it is, text files as
// plain text, SPEC section 14). The mock has no folders, so small generated content stands in:
// a short text for text files and a one-colour PNG for pictures, both as `data:` addresses (no
// cleanup, nothing to revoke). Videos have no generated stand-in (an MP4 needs a real encoder), so
// they keep the real server's address and a `<video>` stays empty, as does any other file type.
import { buildFileUrl } from "../http";
import type { FileUrlOptions } from "../api";

const PICTURE = /\.(png|jpe?g|webp|gif)$/i;
const TEXT = /\.(txt|md|log)$/i;

/** The last part of a video id (`<channel>/<video>`) is the video's name. */
function videoName(videoId: string): string {
  return videoId.slice(videoId.lastIndexOf("/") + 1);
}

function fileName(path: string): string {
  return path.slice(path.lastIndexOf("/") + 1);
}

/** The text of a generated text file; `meta.txt` and `info.txt` read like the agent wrote them. */
export function mockText(videoId: string, path: string): string {
  const name = videoName(videoId);
  switch (fileName(path).toLowerCase()) {
    case "meta.txt":
      return [
        `Title: ${name} - an honest review`,
        "Description: What it is, what it did for me and who it is for.",
        "Tags: review, honest, results, routine",
        "",
      ].join("\n");
    case "info.txt":
      return [
        `Video: ${name}`,
        "Product: Example Serum",
        "Notes: Keep the intro short and open with the result.",
        "",
      ].join("\n");
    default:
      return `${fileName(path)}\n\nGenerated by the mock backend for ${name}.\n`;
  }
}

let crcTable: Uint32Array | null = null;

function crc32(bytes: Uint8Array): number {
  crcTable ??= Uint32Array.from({ length: 256 }, (_, n) => {
    let c = n;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    return c >>> 0;
  });
  let crc = 0xffffffff;
  for (const byte of bytes) crc = (crcTable[(crc ^ byte) & 0xff] ?? 0) ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

function adler32(bytes: Uint8Array): number {
  let a = 1;
  let b = 0;
  for (const byte of bytes) {
    a = (a + byte) % 65521;
    b = (b + a) % 65521;
  }
  return ((b << 16) | a) >>> 0;
}

function chunk(type: string, data: Uint8Array): Uint8Array {
  const out = new Uint8Array(12 + data.length);
  const view = new DataView(out.buffer);
  view.setUint32(0, data.length);
  for (let i = 0; i < 4; i += 1) out[4 + i] = type.charCodeAt(i);
  out.set(data, 8);
  view.setUint32(8 + data.length, crc32(out.subarray(4, 8 + data.length)));
  return out;
}

/** A valid 16 by 9 RGB PNG of one colour (stored, not compressed: it stays a few hundred bytes). */
export function solidPng(red: number, green: number, blue: number): Uint8Array {
  const width = 16;
  const height = 9;
  const row = [0, ...Array.from({ length: width }, () => [red, green, blue]).flat()];
  const raw = Uint8Array.from(Array.from({ length: height }, () => row).flat());
  // zlib: header, one final stored block, Adler-32.
  const zlib = new Uint8Array(2 + 5 + raw.length + 4);
  const zview = new DataView(zlib.buffer);
  zlib.set([0x78, 0x01, 0x01], 0);
  zview.setUint16(3, raw.length, true);
  zview.setUint16(5, ~raw.length & 0xffff, true);
  zlib.set(raw, 7);
  zview.setUint32(7 + raw.length, adler32(raw));
  const header = new Uint8Array(13);
  const hview = new DataView(header.buffer);
  hview.setUint32(0, width);
  hview.setUint32(4, height);
  header.set([8, 2, 0, 0, 0], 8); // 8 bit, RGB, deflate, no filter beyond per row, no interlace
  const parts = [
    Uint8Array.of(0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a),
    chunk("IHDR", header),
    chunk("IDAT", zlib),
    chunk("IEND", new Uint8Array(0)),
  ];
  const png = new Uint8Array(parts.reduce((sum, part) => sum + part.length, 0));
  let at = 0;
  for (const part of parts) {
    png.set(part, at);
    at += part.length;
  }
  return png;
}

/** A calm colour that differs by file, so several thumbnails are told apart. */
function pictureColour(path: string): [number, number, number] {
  let hash = 0;
  for (const ch of path) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  const palette: [number, number, number][] = [
    [96, 125, 139],
    [121, 134, 203],
    [77, 182, 172],
    [255, 183, 77],
    [240, 98, 146],
    [129, 199, 132],
  ];
  return palette[hash % palette.length] ?? [96, 125, 139];
}

function toBase64(bytes: Uint8Array): string {
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary);
}

/** The mock's `Api.fileUrl`: a `data:` address for text and pictures, else the real route. */
export function mockFileUrl(videoId: string, path: string, options: FileUrlOptions = {}): string {
  if (PICTURE.test(path)) {
    return `data:image/png;base64,${toBase64(solidPng(...pictureColour(path)))}`;
  }
  if (TEXT.test(path)) {
    return `data:text/plain;charset=utf-8,${encodeURIComponent(mockText(videoId, path))}`;
  }
  return buildFileUrl(videoId, path, options);
}
