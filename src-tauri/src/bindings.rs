//! The tauri-specta builder: the single registration point for every command and event, and the
//! generator of the TypeScript bindings in `src/lib/bindings.ts`.
//!
//! Regenerate the bindings after changing a command, an event or a type in `model.rs`:
//! `npm run gen:types` (runs the `bindings_are_up_to_date` test with `VIDAI_UPDATE_BINDINGS=1`).
//! `cargo test` (part of `npm run check`) fails while the committed bindings are stale.

use specta_typescript::Typescript;
use tauri::Wry;
use tauri_specta::{Builder, collect_commands};

use crate::commands::{archive, jobs, library, opencode, settings, system};
use crate::error::AppError;
use crate::events;

/// Path of the generated bindings, relative to `src-tauri`.
pub const BINDINGS_PATH: &str = "../src/lib/bindings.ts";

/// Every command of SPEC section 5 and every event, registered once.
pub fn builder() -> Builder<Wry> {
    Builder::<Wry>::new()
        .commands(collect_commands![
            // settings.rs
            settings::get_settings,
            settings::set_editing_folder,
            settings::update_general_settings,
            settings::update_appearance,
            settings::set_no_sleep,
            settings::set_model_selection,
            settings::get_default_prompt,
            settings::add_channel,
            settings::create_channel,
            settings::update_channel,
            settings::remove_channel,
            settings::reorder_channels,
            settings::export_settings,
            settings::import_settings,
            settings::get_toolkit_status,
            settings::create_own_toolkit,
            settings::set_active_toolkit,
            // library.rs
            library::get_library,
            library::set_video_type_override,
            library::get_video_inputs,
            // archive.rs
            archive::archive_video,
            archive::unarchive_video,
            archive::get_archived,
            archive::get_edit_log,
            // jobs.rs
            jobs::start_edit,
            jobs::pause_job,
            jobs::continue_job,
            jobs::stop_job,
            jobs::re_edit,
            jobs::render_final,
            jobs::start_job_now,
            jobs::get_job_log,
            jobs::confirm_quit,
            // system.rs
            system::check_system,
            system::open_claude_login,
            system::open_claude_install,
            system::get_claude_info,
            system::get_usage,
            system::open_path,
            system::reveal_path,
            // opencode.rs
            opencode::get_api_key_statuses,
            opencode::set_api_key,
            opencode::clear_api_key,
            opencode::set_setup,
            opencode::set_api_base_url,
            opencode::set_api_model,
            opencode::set_api_effort,
            opencode::get_api_models,
            opencode::test_api,
            opencode::get_opencode_usage,
            opencode::get_claude_routing,
            opencode::get_opencode2_cli,
            opencode::open_opencode2_install,
            opencode::retry_secrets,
        ])
        .events(events::all())
        .typ::<AppError>()
        // One TypeScript type per Rust type: the serialize and deserialize shapes only differ in
        // `#[serde(default)]` fields, and the UI always sends complete objects.
        .disable_serde_phases()
}

/// The TypeScript exporter configuration.
pub fn typescript() -> Typescript {
    Typescript::default().header(
        "// Generated by tauri-specta from src-tauri/src (see bindings.rs). Do not edit by hand.\n\
         // Regenerate with `npm run gen:types`.\n",
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;

    /// Fails when `src/lib/bindings.ts` does not match the Rust types and commands.
    /// With `VIDAI_UPDATE_BINDINGS=1` it rewrites the file instead.
    #[test]
    fn bindings_are_up_to_date() {
        let committed = Path::new(env!("CARGO_MANIFEST_DIR")).join(BINDINGS_PATH);
        let dir = tempfile::TempDir::new().unwrap();
        let fresh = dir.path().join("bindings.ts");
        builder()
            .export(typescript(), &fresh)
            .expect("export TypeScript bindings");
        let fresh = std::fs::read_to_string(&fresh).unwrap();
        if std::env::var_os("VIDAI_UPDATE_BINDINGS").is_some() {
            crate::store::write_atomic(&committed, fresh.as_bytes()).unwrap();
            return;
        }
        let current = std::fs::read_to_string(&committed).unwrap_or_default();
        assert!(
            current == fresh,
            "src/lib/bindings.ts is stale. Run `npm run gen:types` and commit the result."
        );
    }
}
